/**
 * Scan nav, API routes, and Drizzle table names into a committed registry snapshot.
 * Run: npm run diagnostics:registry
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

type NavScan = { href: string; label: string; permission: string | null };

function walk(dir: string, out: string[] = []): string[] {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function scanNav(src: string): NavScan[] {
  const items: NavScan[] = [];
  const blockRe =
    /\{\s*href:\s*"([^"]+)"\s*,\s*label:\s*"([^"]+)"\s*,\s*icon:\s*"[^"]+"(?:\s*,\s*permission:\s*"([^"]+)")?\s*\}/g;
  let m: RegExpExecArray | null;
  while ((m = blockRe.exec(src))) {
    items.push({ href: m[1], label: m[2], permission: m[3] ?? null });
  }

  const multiRe =
    /href:\s*"([^"]+)"[\s\S]*?label:\s*"([^"]+)"[\s\S]*?(?:permission:\s*"([^"]+)")?/g;
  const seen = new Set(items.map((i) => i.href));
  while ((m = multiRe.exec(src))) {
    if (seen.has(m[1])) continue;
    if (!m[1].startsWith("/")) continue;
    items.push({ href: m[1], label: m[2], permission: m[3] ?? null });
    seen.add(m[1]);
  }
  return items.sort((a, b) => a.href.localeCompare(b.href));
}

function scanApiRoutes(): string[] {
  const apiRoot = path.join(ROOT, "app", "api");
  const files = walk(apiRoot).filter((f) => f.endsWith(`${path.sep}route.ts`));
  return files
    .map((f) => {
      const rel = path.relative(apiRoot, path.dirname(f)).replace(/\\/g, "/");
      const suffix = rel === "" ? "" : `/${rel}`;
      return `/api${suffix}`.replace(/\[([^\]]+)\]/g, ":$1");
    })
    .sort();
}

function scanTables(src: string): string[] {
  const names = new Set<string>();
  const re = /pgTable\(\s*"([a-z0-9_]+)"/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(src))) names.add(m[1]);
  return [...names].sort();
}

const navSrc = fs.readFileSync(path.join(ROOT, "lib", "nav.ts"), "utf8");
const schemaSrc = fs.readFileSync(path.join(ROOT, "lib", "db", "schema.ts"), "utf8");

const payload = {
  generatedAt: new Date().toISOString(),
  nav: scanNav(navSrc),
  apiRoutes: scanApiRoutes(),
  tables: scanTables(schemaSrc),
};

const outFile = path.join(ROOT, "lib", "diagnostics", "registry.generated.ts");
const body = `/* Generated by scripts/generate-module-registry.ts. Do not edit by hand. */
/* eslint-disable */
export const registryGeneratedAt = ${JSON.stringify(payload.generatedAt)};

export const generatedNav: Array<{ href: string; label: string; permission: string | null }> = ${JSON.stringify(payload.nav, null, 2)};

export const generatedApiRoutes: string[] = ${JSON.stringify(payload.apiRoutes, null, 2)};

export const generatedTables: string[] = ${JSON.stringify(payload.tables, null, 2)};
`;

fs.writeFileSync(outFile, body);
console.log(
  `Wrote ${path.relative(ROOT, outFile)} (nav=${payload.nav.length} api=${payload.apiRoutes.length} tables=${payload.tables.length})`,
);
