import "server-only";

import { eq } from "drizzle-orm";
import { getDb } from "@/lib/db";
import { firms } from "@/lib/db/schema";
import type { FirmExportBranding } from "@/lib/export/types";

const LEXZIM_FOOTER = "Generated by LexZim";

/** Firm letterhead data for branded exports. */
export async function getFirmExportBranding(firmId: string): Promise<FirmExportBranding> {
  const db = getDb();
  const rows = await db.select().from(firms).where(eq(firms.id, firmId)).limit(1);
  const firm = rows[0];
  if (!firm) {
    return {
      firmId,
      firmName: "LexZim Firm",
      logoUrl: null,
      addressLines: [],
      contactEmail: null,
      contactPhone: null,
      footerNote: LEXZIM_FOOTER,
    };
  }

  const addressLines = [
    firm.addressLine1,
    firm.addressLine2,
    [firm.city, firm.country].filter(Boolean).join(", ") || null,
  ].filter((line): line is string => Boolean(line?.trim()));

  return {
    firmId: firm.id,
    firmName: firm.name,
    logoUrl: firm.logoUrl,
    addressLines,
    contactEmail: firm.contactEmail,
    contactPhone: firm.contactPhone,
    footerNote: LEXZIM_FOOTER,
  };
}
